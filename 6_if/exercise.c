// ### 🧪 Exercise 2: Check Adult Age
// Write a C program that:
// 1. Creates an integer variable:
// int age = 20;

// 2. Use `if` to check whether the age is **greater than or equal to 18**.

// 3. If the condition is true, print:
    // You are an adult.

// ### Expected Output
    // You are an adult.
// **Rule:** Use only `if`. Don't use `else` yet.

#include <stdio.h>

int main() {
    int age = 20; 

    if (age >= 18) {
        printf("You are an adult"); 
    }

    return 0; 
}